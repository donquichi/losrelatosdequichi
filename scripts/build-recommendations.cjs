// One reviewed product list supplies the homepage and every episode sidebar.
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const input=JSON.parse(fs.readFileSync(path.join(root,'ghost/recommendations.json'),'utf8'));
if(input.version!==1||!Array.isArray(input.items)||input.items.length>12)throw Error('Expected version 1 and at most twelve curated items');
function escaped(value,max) {
    if(typeof value!=='string'||!value.trim()||value.length>max||/[\u0000-\u001f{}]/.test(value))throw Error('Invalid recommendation text');
    return value.replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
}
const ids=new Set(),urls=new Set();
const items=input.items.map(item=>{
    if(!/^[a-z0-9-]{1,60}$/.test(item.id)||ids.has(item.id)||typeof item.enabled!=='boolean')throw Error('Invalid or duplicate recommendation ID');
    ids.add(item.id);
    const url=new URL(item.url);
    if(url.protocol!=='https:'||url.username||url.password||url.port||url.hash||!['link.amazon','amzn.to','www.amazon.com','amazon.com'].includes(url.hostname))throw Error('Use an original HTTPS Amazon affiliate link');
    if(['www.amazon.com','amazon.com'].includes(url.hostname)&&url.searchParams.get('tag')!=='relatosquichi-20')throw Error('Full Amazon links must retain the verified Associates tag');
    if(urls.has(item.url))throw Error('Duplicate product link');urls.add(item.url);
    return {...item,title:escaped(item.title,100),description:escaped(item.description,240),href:escaped(item.url,2048)};
}).filter(item=>item.enabled);
const output='{{! Generated by scripts/build-recommendations.cjs from ghost/recommendations.json. }}\n'+(items.length?`<section id="quichi-recomendaciones" class="quichi-recommendations" aria-labelledby="quichi-recommendations-title">
    <h3 id="quichi-recommendations-title">Recomendaciones de Quichi</h3>
    <p class="quichi-affiliate-disclosure">Enlaces de afiliado: puedo recibir una comisión si compras a través de estos enlaces.</p>
    <p class="quichi-amazon-disclosure" lang="en">As an Amazon Associate I earn from qualifying purchases.</p>
    <div class="quichi-recommendation-list">
${items.map(item=>`        <article class="quichi-recommendation-item" data-recommendation="${item.id}">
            <h4>${item.title}</h4>
            <p>${item.description}</p>
            <a href="${item.href}" target="_blank" rel="sponsored noopener">Ver en Amazon <span class="quichi-newtab">(abre una nueva pestaña)</span><span aria-hidden="true">↗</span></a>
        </article>`).join('\n')}
    </div>
</section>\n`:'');
const outputs={
    'amazon-recommendations.hbs':output,
    'recommendations-link.hbs':items.length?'<li><a href="{{@site.url}}/#quichi-recomendaciones">Quichi recomienda</a></li>\n':''
};
for(const [name,content] of Object.entries(outputs)) {
    const file=path.join(root,'theme/V64/partials/components',name);
    if(process.argv.includes('--check')){if(fs.readFileSync(file,'utf8').replace(/\r\n/g,'\n')!==content)throw Error('Run node scripts/build-recommendations.cjs after updating the product list');}
    else fs.writeFileSync(file,content);
}
console.log(JSON.stringify({activeRecommendations:items.length,sharedSidebar:true,result:'passed'}));
